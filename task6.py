#Создаём список чисел
numbers = [10, 5, 20, 8, 20, 15]

#Удаляем повторяющиеся числа
numbers = list(set(numbers))

#Снова сортируем, так как set не сохраняет порядок
numbers.sort(reverse=True)

#Проверяем, есть ли минимум два разных числа
if len(numbers) >= 2:
    print("Второй по величине элемент:", numbers[1])
else:
    print("Недостаточно уникальных элементов.")
